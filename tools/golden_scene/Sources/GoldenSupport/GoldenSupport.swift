import Foundation

/// Golden values cross from Swift to March as text tokens, because neither a
/// UInt64 nor an exact Double survives a March literal on the JS target.
/// Every token below has a matching reader in test/support/golden_io.march.

/// A UInt64 as 16 lowercase hex digits. March reads it as two 32-bit limbs.
public func u64(_ x: UInt64) -> String { hex64(x) }

/// A Double as its IEEE-754 bit pattern, 16 lowercase hex digits. Exact for
/// every value, including -0.0, infinities and NaN.
public func f64(_ x: Double) -> String { hex64(x.bitPattern) }

/// An Int as plain decimal. Rejects anything the JS target cannot hold exactly.
public func i(_ x: Int) -> String {
    precondition(abs(x) < (1 << 53), "golden int \(x) is outside the JS-safe range; emit it with u64")
    return String(x)
}

/// A Bool as 1 or 0.
public func b(_ x: Bool) -> String { x ? "1" : "0" }

private func hex64(_ x: UInt64) -> String {
    let s = String(x, radix: 16)
    return String(repeating: "0", count: 16 - s.count) + s
}

/// Collects golden lines and writes them as one generated March module.
/// A line is space-separated tokens; the first token names the record kind.
public struct GoldenFile {
    public let module: String
    public let source: String
    /// The make target that rebuilds this file, named in its header.
    public let regenerate: String
    public private(set) var lines: [String] = []

    /// `module` is the March module name without its prefix: "Rng" writes
    /// `mod Golden.Rng` to test/golden/rng.march.
    public init(module: String, regenerate: String = "make golden", source: String = #fileID) {
        self.module = module
        self.regenerate = regenerate
        self.source = source
    }

    public mutating func line(_ tokens: String...) { lines.append(tokens.joined(separator: " ")) }
    public mutating func line(_ tokens: [String]) { lines.append(tokens.joined(separator: " ")) }

    /// Long modules are split into chunks of `perChunk` lines so that no single
    /// March function holds a huge literal.
    public func marchSource(perChunk: Int = 500) -> String {
        var out = "mod Golden.\(module) do\n\n"
        out += "  -- GENERATED by tools/golden (\(source)). Do not edit; run `\(regenerate)`.\n"
        let chunks = stride(from: 0, to: lines.count, by: perChunk).map {
            Array(lines[$0..<min($0 + perChunk, lines.count)])
        }
        for (n, chunk) in chunks.enumerated() {
            out += "  fn chunk_\(n)() : String do\n    \""
            out += chunk.map { $0 + "\\n" }.joined()
            out += "\"\n  end\n\n"
        }
        out += "  fn chunks() : List(String) do\n    ["
        out += (0..<chunks.count).map { "chunk_\($0)()" }.joined(separator: ", ")
        out += "]\n  end\n\n  fn line_count() : Int do\n    \(lines.count)\n  end\n\nend\n"
        return out
    }

    /// Writes to `<project>/test/golden/<module lowercased>.march`. The project
    /// root comes from argv[1], which `make golden` passes.
    public func write() throws {
        guard CommandLine.arguments.count > 1 else {
            FileHandle.standardError.write(Data("usage: golden-x <project root>\n".utf8))
            exit(2)
        }
        let root = URL(fileURLWithPath: CommandLine.arguments[1])
        let path = root.appendingPathComponent("test/golden/\(module.lowercased()).march")
        try marchSource().write(to: path, atomically: true, encoding: .utf8)
        print("wrote \(lines.count) lines to \(path.path)")
    }
}
